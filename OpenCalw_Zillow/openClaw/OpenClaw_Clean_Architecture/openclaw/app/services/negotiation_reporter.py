DAILY_REPORT_KEY_PREFIX = "openclaw:neg-report:last-day:"

_ESTADOS_ACTIVOS = frozenset({"propuesta", "contraoferta", "aceptada"})


def resolver_zona_horaria(tz_name: str | None = None) -> tzinfo:
    """Resuelve la zona horaria IANA con respaldo seguro a UTC-5 si falta tzdata."""
    nombre = (tz_name or settings.NEGOTIATION_REPORT_TZ or "America/New_York").strip()
    try:
        return ZoneInfo(nombre)
    except ZoneInfoNotFoundError:
        if any(tok in nombre.lower() for tok in ("new_york", "bogota", "lima", "est", "eastern")):
            return timezone(timedelta(hours=-5))
        return UTC


def estrategia_seller_financing_resumen() -> str:
    """Resumen en español de la estrategia activa para el operador."""
    dp_min = settings.NEGOTIATION_DOWN_PAYMENT_MIN_USD
    dp_max = settings.NEGOTIATION_DOWN_PAYMENT_MAX_USD
    bonus_m = settings.NEGOTIATION_BONUS_EXTRA_MONTHS
    return (
        f"Seller Financing · Cuota inicial objetivo ${dp_min:,.0f}–${dp_max:,.0f} USD · "
        f"Bono de +{bonus_m} cuotas mensuales adicionales al finalizar el pago del crédito · "
        "Comunicación al vendedor en inglés (EE. UU.)."
    )


def construir_mensaje_ingles_vendedor(
    *,
    ubicacion: str,
    url_origen: str,
    precio_publicado_usd: float,
    precio_oferta_usd: float,
    condiciones_extra: str | None = None,
    contacto_vendedor: str | None = None,
    down_payment_min_usd: float | None = None,
    down_payment_max_usd: float | None = None,
    bonus_extra_months: int | None = None,
) -> str:
    """Redacta el mensaje inicial en inglés para el vendedor/agente en EE. UU."""
    dp_min = (
        down_payment_min_usd
        if down_payment_min_usd is not None
        else settings.NEGOTIATION_DOWN_PAYMENT_MIN_USD
    )
    dp_max = (
        down_payment_max_usd
        if down_payment_max_usd is not None
        else settings.NEGOTIATION_DOWN_PAYMENT_MAX_USD
    )
    bonus_m = (
        bonus_extra_months
        if bonus_extra_months is not None
        else settings.NEGOTIATION_BONUS_EXTRA_MONTHS
    )
    saludo = f"Hello {contacto_vendedor}," if contacto_vendedor else "Hello,"
    lineas = [
        saludo,
        "",
        f"I am interested in purchasing the property at {ubicacion} ({url_origen}).",
        (
            f"Based on the listed price of ${precio_publicado_usd:,.0f}, I would like to propose "
            f"a purchase price of ${precio_oferta_usd:,.0f} structured with Seller Financing."
        ),
        (
            f"To make this a smooth, win-win transaction, I am looking for a low down payment "
            f"in the range of ${dp_min:,.0f} to ${dp_max:,.0f} USD."
        ),
        (
            f"In exchange for the lower down payment and seller-financed terms, I am willing to "
            f"offer an additional bonus of {bonus_m} extra monthly payments paid after the full "
            "payoff of the seller-financed note."
        ),
    ]
    if condiciones_extra and condiciones_extra.strip():
        lineas.append(f"Additional terms / notes: {condiciones_extra.strip()}")

    lineas.extend(
        [
            "",
            (
                "Would the seller be open to discussing seller financing terms and reviewing a "
                "non-binding Letter of Intent? Please let me know the best way to connect."
            ),
            "",
            "Best regards,",
            "[Non-binding inquiry draft generated by OpenClaw — subject to formal written agreement and inspection]",
        ]
    )
    return "\n".join(lineas)


def construir_respuesta_ingles_vendedor(
    *,
    ubicacion: str,
    mensaje_vendedor: str,
    precio_oferta_actual_usd: float,
    down_payment_min_usd: float | None = None,
    down_payment_max_usd: float | None = None,
    bonus_extra_months: int | None = None,
) -> tuple[str, dict[str, object]]:
    """Analiza un mensaje del vendedor y redacta un borrador de respuesta en inglés."""
    dp_min = (
        down_payment_min_usd
        if down_payment_min_usd is not None
        else settings.NEGOTIATION_DOWN_PAYMENT_MIN_USD
    )
    dp_max = (
        down_payment_max_usd
        if down_payment_max_usd is not None
        else settings.NEGOTIATION_DOWN_PAYMENT_MAX_USD
    )
    bonus_m = (
        bonus_extra_months
        if bonus_extra_months is not None
        else settings.NEGOTIATION_BONUS_EXTRA_MONTHS
    )

    extraccion = extraer_datos_comerciales_mensaje(mensaje_vendedor)
    texto_low = (mensaje_vendedor or "").lower()
    menciona_sf = any(
        tok in texto_low
        for tok in ("seller financ", "owner financ", "carry", "note", "installment", "terms")
    )
    menciona_down = any(tok in texto_low for tok in ("down payment", "downpayment", "down", "cash"))

    precio_ref = extraccion.precio_solicitado_usd or precio_oferta_actual_usd
    bloques = [
        f"Hello, thank you for your reply regarding {ubicacion}.",
    ]
    if extraccion.precio_solicitado_usd is not None:
        bloques.append(
            f"We reviewed your price indication of ${extraccion.precio_solicitado_usd:,.0f} "
            f"alongside our current offer of ${precio_oferta_actual_usd:,.0f}."
        )
    if menciona_sf:
        bloques.append("We appreciate your openness to discussing seller financing terms.")
    else:
        bloques.append(
            "We would still love to explore a Seller Financing structure that maximizes total "
            "long-term payout for the seller while keeping closing simple and fast."
        )
    if menciona_down:
        bloques.append(
            f"Our goal is to keep the initial down payment between ${dp_min:,.0f} and "
            f"${dp_max:,.0f} USD. To compensate the seller for accepting a lower down payment, "
            f"we include a guaranteed bonus of {bonus_m} additional monthly payments after full "
            "payoff of the note."
        )
    else:
        bloques.append(
            f"Specifically, we are proposing ${dp_min:,.0f}–${dp_max:,.0f} USD down at closing "
            f"plus a bonus of {bonus_m} extra monthly payments after the loan is paid off "
            f"(target price: ${precio_ref:,.0f})."
        )
    if extraccion.dias_cierre_solicitados is not None:
        bloques.append(
            f"We can work toward your requested {extraccion.dias_cierre_solicitados}-day closing timeline."
        )

    bloques.append(
        "Please let us know what monthly payment and interest rate structure would work best for "
        "the seller so we can prepare a non-binding written Letter of Intent."
    )
    bloques.append(
        "[Non-binding reply draft in English — review and send manually to the seller/agent]"
    )

    analisis: dict[str, object] = {
        "precio_solicitado_usd": extraccion.precio_solicitado_usd,
        "dias_cierre_solicitados": extraccion.dias_cierre_solicitados,
        "menciona_as_is": extraccion.menciona_as_is,
        "menciona_inspeccion": extraccion.menciona_inspeccion,
        "menciona_seller_financing": menciona_sf,
        "menciona_down_payment": menciona_down,
        "confianza_extraccion": extraccion.confianza_extraccion,
        "atributos_protegidos_ignorados": extraccion.atributos_protegidos_ignorados,
    }
    return "\n\n".join(bloques), analisis


def generar_reporte_negociaciones(
    filas: Sequence[tuple[Oferta, Propiedad, Sequence[OfertaEvento]]],
    *,
    fecha_local: datetime,
) -> str:
    """Construye el reporte diario de estado de negociaciones para el operador."""
    activas = [f for f in filas if f[0].estado in _ESTADOS_ACTIVOS]
    cerradas = [f for f in filas if f[0].estado not in _ESTADOS_ACTIVOS]
    total_mensajes_vendedor = sum(
        sum(1 for ev in eventos if ev.actor == "vendedor") for _, _, eventos in filas
    )

    lineas = [
        f"📊 REPORTE DIARIO DE NEGOCIACIONES — {fecha_local.strftime('%Y-%m-%d %H:%M %Z').strip()}",
        f"Estrategia activa: {estrategia_seller_financing_resumen()}",
        (
            f"Resumen: {len(activas)} activas | {len(cerradas)} cerradas/rechazadas | "
            f"{total_mensajes_vendedor} comunicaciones del vendedor registradas"
        ),
    ]

    if not activas:
        lineas.extend(
            [
                "",
                "No hay negociaciones activas en este momento.",
                "Aprueba una propiedad en Telegram con ✅ Aprobar / Negociar para iniciar una.",
            ]
        )
        return "\n".join(lineas)

    lineas.append("")
    for idx, (oferta, prop, eventos) in enumerate(activas, start=1):
        prefijo = str(oferta.id)[:8]
        contacto = extraer_contacto_vendedor(prop.descripcion_cruda) or (
            f"Vendedor/agente ({prop.plataforma})"
        )
        msgs_vendedor = [ev for ev in eventos if ev.actor == "vendedor"]
        ultimo_ev = eventos[0] if eventos else None
        ultimo_txt = (
            f"{ultimo_ev.actor}: {(ultimo_ev.notas or ultimo_ev.estado_nuevo)[:110]}"
            if ultimo_ev is not None
            else "Sin comunicaciones registradas aún"
        )
        contra_txt = (
            f" | Contraoferta: ${float(oferta.importe_contraoferta_usd):,.0f}"
            if oferta.importe_contraoferta_usd is not None
            else ""
        )
        lineas.append(
            f"{idx}. [{oferta.estado.upper()}] {prop.ubicacion}\n"
            f"   ID: {prefijo} | Oferta: ${float(oferta.importe_usd):,.0f}{contra_txt}\n"
            f"   Contacto: {contacto} | Publicación: {prop.url_origen}\n"
            f"   Comunicaciones vendedor: {len(msgs_vendedor)} | Último: {ultimo_txt}"
        )

    lineas.extend(
        [
            "",
            "Comandos: /msg <ID_8_chars> <mensaje del vendedor> para registrar y generar respuesta en inglés · /reporte para actualizar ahora.",
        ]
    )
    return "\n".join(lineas)


async def consultar_negociaciones_y_generar_reporte(
    *,
    fecha_local: datetime | None = None,
) -> str:
    """Consulta PostgreSQL y construye el reporte consolidado de negociaciones."""
    tz = resolver_zona_horaria()
    ahora = fecha_local if fecha_local is not None else datetime.now(tz)

    async with unidad_de_trabajo() as unidad:
        res_ofertas = await unidad.sesion.execute(
            select(Oferta, Propiedad)
            .join(Propiedad, Propiedad.id == Oferta.propiedad_id)
            .order_by(Oferta.actualizada_en.desc())
            .limit(50)
        )
        pares = list(res_ofertas.all())
        oferta_ids = [of.id for of, _ in pares]

        eventos_por_oferta: dict[object, list[OfertaEvento]] = {}
        if oferta_ids:
            res_ev = await unidad.sesion.execute(
                select(OfertaEvento)
                .where(OfertaEvento.oferta_id.in_(oferta_ids))
                .order_by(OfertaEvento.ocurrido_en.desc())
            )
            for ev in res_ev.scalars().all():
                eventos_por_oferta.setdefault(ev.oferta_id, []).append(ev)

    filas = [(of, prop, eventos_por_oferta.get(of.id, [])) for of, prop in pares]
    return generar_reporte_negociaciones(filas, fecha_local=ahora)


async def enviar_reporte_diario_si_corresponde(
    *,
    now_utc: datetime | None = None,
    force: bool = False,
    notifier: TelegramNotifierAdapter | None = None,
) -> bool:
    """Envía el reporte diario por Telegram a partir de las 11:00 AM (1 vez por día)."""
    tz = resolver_zona_horaria()
    ahora_utc = now_utc if now_utc is not None else datetime.now(UTC)
    ahora_local = ahora_utc.astimezone(tz)

    objetivo_min = settings.NEGOTIATION_REPORT_HOUR * 60 + settings.NEGOTIATION_REPORT_MINUTE
    actual_min = ahora_local.hour * 60 + ahora_local.minute
    if not force and actual_min < objetivo_min:
        return False

    dia_clave = f"{DAILY_REPORT_KEY_PREFIX}{ahora_local.date().isoformat()}"
    if not force:
        reclamado = await redis_client.set(dia_clave, "1", nx=True, ex=172800)
        if not reclamado:
            return False

    chat_id = str(settings.TG_CHAT_ID or "").strip()
    if not chat_id:
        logger.warning("reporte_diario_sin_chat_id")
        return False

    reporte = await consultar_negociaciones_y_generar_reporte(fecha_local=ahora_local)
    bot = notifier if notifier is not None else TelegramNotifierAdapter()
    ok, err = await bot.send_message(chat_id, reporte)
    if not ok:
        if not force:
            await redis_client.delete(dia_clave)
        logger.warning("reporte_diario_error_envio", extra={"error": err})
        return False

    logger.info(
        "reporte_diario_negociaciones_enviado",
        extra={"fecha_local": ahora_local.isoformat(), "force": force},
    )
    return True
