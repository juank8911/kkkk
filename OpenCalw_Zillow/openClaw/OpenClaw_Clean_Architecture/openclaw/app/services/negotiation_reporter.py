"""Estrategia Seller Financing en inglés (EE. UU.) y reporte diario 11:00 AM de negociaciones.

Reglas de negocio:
- Toda comunicación dirigida a vendedores/agentes en EE. UU. se redacta en inglés.
- Estrategia por defecto: solicitar Seller Financing con cuota inicial baja objetivo
  de $5,000 a $7,000 USD, ofreciendo como incentivo un bono de 6 cuotas mensuales
  adicionales pagadas después de completar el pago total del crédito.
- Monitoreo de comunicaciones con el vendedor en `oferta_eventos` y reporte diario
  automático a las 11:00 AM (hora configurada en `NEGOTIATION_REPORT_TZ`).
"""

